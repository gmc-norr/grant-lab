# scripts/gen_routes.py
"""Generate route-ownership artifacts from frontend/routes.json.

Single source of truth → a Python module (FastAPI serving) and a TS module
(Vite proxy + React Router). Run in CI/pre-build.

SPA ownership is an EXACT/PATTERN match, never a prefix/`startswith` test.
BACKEND_PREFIXES / is_backend_route are emitted as a documented prefix set and a
future explicit-carve-out helper; they are currently NOT consulted by the serving
or proxy path (the dev proxy is default-to-backend, the prod catch-all keys off
is_spa_route alone). Never used to decide SPA ownership.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = json.loads((ROOT / "frontend/routes.json").read_text())
# Route paths are URL prefixes and never legitimately contain a double-quote.
# json.dumps (used for both .py and .ts output) would escape an embedded " as
# \", which `ruff format` then rewrites to single quotes — breaking the
# "ruff-clean / idempotent" guarantee below. Reject that input class up front so
# the guarantee holds for every route the generator will actually accept.
for _r in [*SRC["spa_routes"], *SRC["backend_prefixes"]]:
    if '"' in _r:
        raise ValueError(f"route contains an unsupported double-quote: {_r!r}")
SPA = sorted(SRC["spa_routes"], key=len, reverse=True)
BACKEND = sorted(SRC["backend_prefixes"], key=len, reverse=True)


LINE_LENGTH = 100


def _py_tuple(prefix: str, items: list[str]) -> str:
    """Render a string tuple exactly as `ruff format` would so the generated
    module is ruff-clean and `gen_routes.py` stays idempotent (re-running never
    produces a diff; CI can't drift). Elements are double-quoted. Ruff keeps a
    collection inline when it fits within the configured line length and
    explodes it (one element per line, trailing comma) otherwise — `prefix` is
    the assignment text on the same line so the fit check matches ruff's."""
    if not items:
        return "()"
    # A 1-tuple needs a trailing comma; a multi-element inline tuple gets none
    # (ruff only keeps the trailing "magic" comma when the collection explodes).
    inner = ", ".join(json.dumps(i) for i in items)
    inline = f"({inner},)" if len(items) == 1 else f"({inner})"
    if len(prefix) + len(inline) <= LINE_LENGTH:
        return inline
    body = "".join(f"    {json.dumps(i)},\n" for i in items)
    return f"(\n{body})"


SPA_PREFIX = "SPA_ROUTES: tuple[str, ...] = "
BACKEND_PREFIX = "BACKEND_PREFIXES: tuple[str, ...] = "

PY = f'''# AUTO-GENERATED by scripts/gen_routes.py — do not edit by hand.
from __future__ import annotations

# SPA-owned page routes (EXACT match; React Router owns client sub-paths beneath).
{SPA_PREFIX}{_py_tuple(SPA_PREFIX, SPA)}
# Backend prefixes — the real top-level prefixes mounted in main.py. Currently
# UNUSED by serving/proxy (dev proxy is default-to-backend; prod catch-all uses
# is_spa_route); kept as a documented set + future carve-out helper. Never used
# to decide SPA ownership.
{BACKEND_PREFIX}{_py_tuple(BACKEND_PREFIX, BACKEND)}


def is_backend_route(path: str) -> bool:
    return any(path == p or path.startswith(p.rstrip("/") + "/") for p in BACKEND_PREFIXES)


def is_spa_route(path: str) -> bool:
    """True only for a manifest SPA-owned page route. A non-root owned route
    matches EXACTLY or via a React-Router client sub-path beneath it; the ROOT
    route "/" owns ONLY itself — never a subtree. So after Plan 3 flips
    SPA_ROUTES to ("/",), is_spa_route("/") is True but "/api/x", "/calls/1",
    "/made-up-page" are all False and fall through to FastAPI's real 404. This
    is deliberately NOT a `startswith("/")`-style match — note that a naive
    `path.startswith(r.rstrip("/") + "/")` collapses to "match everything" the
    moment the owned route is "/" (rstrip → "", startswith("/") → always True),
    which is exactly the bug this root special-case prevents."""
    for r in SPA_ROUTES:
        if r == "/":
            if path == "/":
                return True
        elif path == r or path.startswith(r.rstrip("/") + "/"):
            return True
    return False
'''

TS = (
    "// AUTO-GENERATED by scripts/gen_routes.py — do not edit by hand.\n"
    f"export const SPA_ROUTES: string[] = {json.dumps(SPA)};\n"
    f"export const BACKEND_PREFIXES: string[] = {json.dumps(BACKEND)};\n"
)

PY_PATH = ROOT / "src/call_manager/web/spa_routes.py"
TS_PATH = ROOT / "frontend/src/routes.gen.ts"


def _write() -> None:
    PY_PATH.write_text(PY)
    (ROOT / "frontend/src").mkdir(parents=True, exist_ok=True)
    TS_PATH.write_text(TS)
    print("wrote spa_routes.py and routes.gen.ts:", {"spa": SPA, "backend": BACKEND})


def _check() -> int:
    """Exit non-zero if the committed artifacts are stale vs frontend/routes.json
    (mirrors scripts/gen_no_build.py --check). Writes nothing, so a forgotten
    regenerate fails CI instead of being silently repaired."""
    stale = [
        str(p.relative_to(ROOT))
        for p, want in ((PY_PATH, PY), (TS_PATH, TS))
        if not p.exists() or p.read_text() != want
    ]
    if stale:
        print(
            "ERROR: generated route artifacts are stale vs frontend/routes.json:\n  "
            + "\n  ".join(stale)
            + "\nRun: uv run python scripts/gen_routes.py",
            file=sys.stderr,
        )
        return 1
    print("route artifacts in sync with routes.json")
    return 0


if __name__ == "__main__":
    if "--check" in sys.argv[1:]:
        raise SystemExit(_check())
    _write()
