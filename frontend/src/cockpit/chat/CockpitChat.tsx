import { useEffect, useMemo, useState } from "react";
import { useParams } from "react-router-dom";
import { useQueryClient } from "@tanstack/react-query";

import { redirectToLogin, redirectToNoAccess } from "../../api/client";
import { useReferences } from "../../api/citations";
import { useEventStream } from "../../api/events";
import { turnStreamUrl, useAckDisclosure, useCancelTurn, useTurns } from "../../api/turns";
import styles from "./CockpitChat.module.css";
import { Composer } from "./Composer";
import { TurnList } from "./TurnList";
import { invalidateArtifact } from "../../api/invalidateArtifact";

type Turn = {
  id: string;
  role: string;
  position: number;
  created_at: string;
  content: unknown;
};

export function CockpitChat() {
  const { id = "" } = useParams();
  const qc = useQueryClient();
  const turns = useTurns(id);
  const references = useReferences(id);
  const refs = Array.isArray(references.data) ? references.data : [];
  const ack = useAckDisclosure(id);
  const d = turns.data;

  const [jobId, setJobId] = useState<string | null>(null);
  // keyed by position for deduplication with history turns
  const [streamed, setStreamed] = useState<Record<number, Turn>>({});

  const cancel = useCancelTurn(id);
  const [cancelNote, setCancelNote] = useState<string | null>(null);

  // Re-attach to an in-flight turn after a reload.
  useEffect(() => {
    if (turns.data?.running_job_id) setJobId(turns.data.running_job_id);
  }, [turns.data?.running_job_id]);

  useEventStream(
    jobId ? turnStreamUrl(id, jobId) : "",
    {
      turn: (data) => {
        const t = data as Turn;
        setStreamed((m) => ({ ...m, [t.position]: t }));
      },
      done: () => {
        setJobId(null);
        setStreamed({});
        setCancelNote(null); // don't let a "too late" note bleed into the next turn
        qc.invalidateQueries({ queryKey: ["turns", id] });
        qc.invalidateQueries({ queryKey: ["proposed-changes", id, "draft"] });
        qc.invalidateQueries({ queryKey: ["proposed-changes", id, "spec"] });
        void invalidateArtifact(qc, id, "draft");
      },
    },
    {
      resetCursorOnUrlChange: true,
      // events.ts classifies a dead stream by probing /api/me, then closes the
      // EventSource so it cannot auto-reconnect. Passing neither callback threw
      // that classification away: the 401/403 branch was dead code, this path
      // never redirected, and the user sat under "Assistant is working…" over a
      // socket that was never coming back — rescued only when the unrelated 15 s
      // Problems poller happened to hit the 401 chokepoint in api/client.
      //
      // Clearing `jobId` is NOT what re-enables the composer: that also reads
      // the cached `running_job_id`, and the turn really is still running
      // server-side. It is here so a re-render during the navigation cannot
      // reopen a stream we have just been told we may not read.
      onExpired: () => {
        setJobId(null);
        redirectToLogin();
      },
      onNoAccess: () => {
        setJobId(null);
        redirectToNoAccess();
      },
    },
  );

  const merged = useMemo(() => {
    const byPos = new Map<number, Turn>();
    for (const t of turns.data?.turns ?? []) byPos.set(t.position, t as Turn);
    for (const t of Object.values(streamed)) byPos.set(t.position, t);
    return [...byPos.values()].sort((a, b) => a.position - b.position);
  }, [turns.data?.turns, streamed]);

  return (
    <aside className={styles.chat} aria-label="Chat">
      <header className={styles.header}>Chat</header>
      <div className={styles.body}>
        {turns.isLoading && <p className={styles.note}>Loading…</p>}
        {d && <TurnList id={id} turns={merged} refs={refs} />}
      </div>
      {d && (
        <footer className={styles.footer}>
          {(() => {
            // Setup phase: the agent chat is unavailable for everyone until activation.
            // Branch on phase FIRST so a viewer (whose disabled_reason is "not_owner")
            // still gets setup messaging, not the active-phase read-only copy.
            if (d.phase === "setup")
              return (
                <p className={styles.note}>The agent chat opens once the workspace is active.</p>
              );
            const reason =
              d.disabled_reason ??
              (!d.can_send ? "not_owner" : d.needs_disclosure ? "needs_disclosure" : null);
            if (reason === "not_owner")
              return <p className={styles.note}>Read-only — only the owner can message the agent.</p>;
            if (reason === "drafting_disabled")
              return <p className={styles.note}>Drafting is currently disabled.</p>;
            if (reason === "needs_disclosure")
              return (
                <div className={styles.disclosure}>
                  <p>
                    Proposals are generated by a hosted model. Don&apos;t paste patient-identifiable
                    data.
                  </p>
                  <button type="button" disabled={ack.isPending} onClick={() => { ack.mutate(); }}>
                    I understand
                  </button>
                </div>
              );
            return (
              <>
                {d.is_owner && (jobId || d.running_job_id) && (
                  <div className={styles.cancelRow}>
                    <span className={styles.note}>Assistant is working…</span>
                    <button
                      type="button"
                      disabled={cancel.isPending}
                      onClick={() => {
                        const jid = jobId ?? d.running_job_id;
                        if (!jid) return;
                        cancel.mutate(jid, {
                          onSuccess: (res) => {
                            if (res?.cancelled) {
                              setJobId(null);
                              setStreamed({});
                              setCancelNote(null);
                            } else {
                              setCancelNote("Too late — the assistant already started.");
                            }
                          },
                        });
                      }}
                    >
                      Cancel
                    </button>
                    {cancelNote && <span className={styles.note}>{cancelNote}</span>}
                  </div>
                )}
                <Composer
                  id={id}
                  refs={refs}
                  disabled={!!jobId || !!d.running_job_id}
                  onSubmitted={(jid) => {
                    setJobId(jid);
                    setCancelNote(null); // a new turn starts clean
                  }}
                />
              </>
            );
          })()}
        </footer>
      )}
    </aside>
  );
}
